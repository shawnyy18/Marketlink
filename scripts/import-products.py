#!/usr/bin/env python3
"""Build the local product catalog from supplier metadata and local images."""

from __future__ import annotations

import html
import json
import re
import shutil
import unicodedata
from pathlib import Path
from urllib.parse import unquote, urlparse
from urllib.request import Request, urlopen


ROOT = Path(__file__).resolve().parents[1]
SOURCE_IMAGES = ROOT.parent / "Yanyan" / "product-images"
OUT_IMAGES = ROOT / "public" / "assets" / "products"
OUT_DATA = ROOT / "src" / "data" / "products.js"
BASE = "https://www.yanyaninternational.com"
CATEGORIES = {
    "snacks": "Snacks",
    "beverages": "Beverages",
    "instant-beverages": "Instant Beverages",
    "cookies": "Cookies & Wafers",
    "chocolates": "Chocolates",
    "bread": "Bread",
}
FEATURED_IDS = {
    "green-peas-snack-0",
    "apple",
    "dark-chocolate-bar",
    "chocolate-chip-1",
    "mixed-snacks",
    "spicy-vinegar-flavor",
    "original-flavor",
    "ube-bread",
}
CARD_RE = re.compile(
    r'<div class="product"><div class="wrapper">.*?'
    r'<a href="(/product/[^"]+)".*?'
    r'<img[^>]+src="([^"]+)"[^>]*?width="(\d+)" height="(\d+)".*?'
    r'<div class="title"><span>(.*?)</span></div>\s*'
    r'<div class="desc">(.*?)</div>',
    re.S,
)


def clean_text(value: str) -> str:
    return html.unescape(re.sub(r"<.*?>", "", value)).strip()


def key(value: str) -> str:
    return unicodedata.normalize("NFC", value).casefold()


def fetch(path: str) -> str:
    request = Request(f"{BASE}{path}", headers={"User-Agent": "Mozilla/5.0"})
    with urlopen(request, timeout=45) as response:
        return response.read().decode("utf-8", errors="replace")


def main() -> None:
    if not SOURCE_IMAGES.is_dir():
        raise SystemExit(f"Local source images were not found at {SOURCE_IMAGES}")

    local_files = {
        key(path.name): path
        for path in SOURCE_IMAGES.iterdir()
        if path.is_file() and not path.name.startswith("._")
    }
    OUT_IMAGES.mkdir(parents=True, exist_ok=True)
    OUT_DATA.parent.mkdir(parents=True, exist_ok=True)

    products: list[dict[str, object]] = []
    seen: set[str] = set()
    for category_slug, category_name in CATEGORIES.items():
        page = fetch(f"/products/{category_slug}")
        for href, source_image, width, height, brand, name in CARD_RE.findall(page):
            product_id = href.rstrip("/").split("/")[-1]
            if product_id in seen:
                continue
            source_name = unquote(Path(urlparse(source_image).path).name)
            local_source = local_files.get(key(source_name))
            if not local_source:
                raise SystemExit(f"No local image matches {source_name!r}")
            extension = local_source.suffix.lower()
            output_name = f"{product_id}{extension}"
            shutil.copy2(local_source, OUT_IMAGES / output_name)
            products.append(
                {
                    "id": product_id,
                    "brand": clean_text(brand),
                    "name": clean_text(name),
                    "category": category_name,
                    "categorySlug": category_slug,
                    "image": f"/assets/products/{output_name}",
                    "width": int(width),
                    "height": int(height),
                    "featured": product_id in FEATURED_IDS,
                }
            )
            seen.add(product_id)

    if len(products) != 114:
        raise SystemExit(f"Expected 114 products, found {len(products)}")

    products.sort(key=lambda item: (str(item["category"]), str(item["brand"]), str(item["name"])))
    contents = (
        "// Generated by scripts/import-products.py from verified supplier metadata.\n"
        "// Images are copied from the adjacent local Yanyan archive; no hotlinks are used.\n"
        f"export const products = {json.dumps(products, ensure_ascii=False, indent=2)};\n\n"
        f"export const categories = {json.dumps(list(CATEGORIES.values()), ensure_ascii=False)};\n"
    )
    OUT_DATA.write_text(contents, encoding="utf-8")
    print(f"Imported {len(products)} products across {len(CATEGORIES)} categories.")


if __name__ == "__main__":
    main()
